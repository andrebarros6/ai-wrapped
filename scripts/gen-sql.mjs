// Bundles sql/ into lib/engine/sql.generated.ts so the browser runs the exact files the CLI runs.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sqlDir = join(root, "sql");
const read = (p) => readFileSync(p, "utf8").replace(/\r\n/g, "\n");

const metrics = readdirSync(join(sqlDir, "metrics"))
  .filter((f) => f.endsWith(".sql"))
  .sort()
  .map((f) => ({ name: f, sql: read(join(sqlDir, "metrics", f)) }));

const body = `// GENERATED by scripts/gen-sql.mjs from sql/ — do not edit.
export const LOAD_SQL: string = ${JSON.stringify(read(join(sqlDir, "00_load.sql")))};

export const METRICS: ReadonlyArray<{ name: string; sql: string }> = ${JSON.stringify(metrics, null, 2)};
`;
writeFileSync(join(root, "lib", "engine", "sql.generated.ts"), body);
console.log(`sql bundled: 00_load.sql + ${metrics.length} metric files`);

// The prompt kit: the text users paste into their own Claude, taken from prompts/*.md.
const between = (text, start, end) => {
  const i = text.indexOf(start);
  const j = text.indexOf(end, i + start.length);
  if (i < 0 || j < 0) throw new Error(`prompt block not found (${start.trim()})`);
  return text.slice(i + start.length, j);
};
const full = read(join(root, "prompts", "full.md"));
const lite = read(join(root, "prompts", "lite.md"));
const fullPrompt = between(full, "````\n", "\n````");
const litePrompt = between(lite, "## Prompt\n\n```\n", "\n```");
writeFileSync(
  join(root, "lib", "prompts.generated.ts"),
  `// GENERATED by scripts/gen-sql.mjs from prompts/ — do not edit.
export const FULL_PROMPT: string = ${JSON.stringify(fullPrompt)};
export const LITE_PROMPT: string = ${JSON.stringify(litePrompt)};
`,
);
console.log("prompts bundled: full.md + lite.md");

// Where scripts/vendor-duckdb.mjs puts DuckDB: a folder named after the package version.
const duckdbVersion = JSON.parse(
  readFileSync(join(root, "node_modules", "@duckdb", "duckdb-wasm", "package.json"), "utf8"),
).version;
writeFileSync(
  join(root, "lib", "engine", "duckdb-assets.generated.ts"),
  `// GENERATED by scripts/gen-sql.mjs — do not edit.
export const DUCKDB_DIR = ${JSON.stringify(`/duckdb/${duckdbVersion}`)};
`,
);
